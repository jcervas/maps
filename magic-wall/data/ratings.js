/** "R+17" -> "rep", "D+3" -> "dem", "EVEN" -> null. */
export function pviParty(pvi) {
  return /^D\+/.test(pvi || "") ? "dem" : (/^R\+/.test(pvi || "") ? "rep" : null);
}

/** "Lean D" -> { strength: "Lean", party: "dem" }; "Toss-up" -> party null. */
export function parseRating(r) {
  const m = /^(Solid|Likely|Lean) ([DR])$/.exec(r || "");
  if (!m) return r === "Toss-up" ? { strength: "Toss-up", party: null } : null;
  return { strength: m[1], party: m[2] === "D" ? "dem" : "rep" };
}

/** The rating for a seat from data/seats.js, or null if unrated. */
export function ratingFor(seat) {
  if (LEG_RATINGS[seat.chamber]) return legRating(seat);
  const t = RATINGS[seat.chamber];
  return t ? t[seat.chamber === "house" ? seat.label : seat.state] || null : null;
}


