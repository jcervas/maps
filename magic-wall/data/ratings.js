const LEG_SCALE = { Solid: "Solid", Uncontested: "Solid", "Very Likely": "Likely", Likely: "Likely",
                    Lean: "Lean", Tilt: "Toss-up" };

/** A legislative seat's StateNavigate label, or null. */
export function legLabel(seat) {
  const t = LEG_RATINGS[seat.chamber];
  // An unexpired term shares its district's unit (West Virginia's Senate).
  const e = t && t[seat.special ? `${seat.unitId}:unexpired` : seat.unitId];
  return e ? e[0] : null;
}

/** StateNavigate's label on the ratings start's scale ("Tilt R" -> "Toss-up"). */
function legRating(seat) {
  const lab = legLabel(seat);
  if (!lab) return null;
  if (lab === "Toss-up") return lab;
  const m = /^(.*) ([DR])$/.exec(lab);
  const s = m && LEG_SCALE[m[1]];
  return !s ? null : s === "Toss-up" ? s : `${s} ${m[2]}`;
}

/** Who rated a seat, for the label beside it. */
export function ratingSource(seat) {
  return LEG_RATINGS[seat.chamber] ? LEG_RATINGS.source : RATINGS.source.split(" ")[0];
}
